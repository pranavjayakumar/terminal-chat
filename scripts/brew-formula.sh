#!/bin/sh
# Regenerate Formula/tc.rb from a published release's signed checksums.txt.
#   scripts/brew-formula.sh vX.Y.Z            # downloads with gh
#   scripts/brew-formula.sh vX.Y.Z DIR        # DIR already holds checksums.txt + checksums.txt.sig
# The SSHSIG on checksums.txt is verified (against the signers embedded in
# internal/release) before any hash is trusted.
set -eu

tag=${1:-}
printf '%s\n' "$tag" | grep -Eq '^v[0-9]+\.[0-9]+\.[0-9]+$' || { echo "usage: $0 vX.Y.Z [DIR]" >&2; exit 2; }
root=$(cd "$(dirname "$0")/.." && pwd)

dir=${2:-}
if [ -z "$dir" ]; then
  dir=$(mktemp -d)
  trap 'rm -rf "$dir"' EXIT
  gh release download "$tag" -R pranavjayakumar/terminal-chat --dir "$dir" --pattern checksums.txt --pattern checksums.txt.sig
fi

# One verified "<os>_<arch> <sha256>" line per build; nothing else is trusted.
sums=$(cd "$root" && GOTOOLCHAIN=local go run ./internal/release/verifyrelease --tag "$tag" "$dir/checksums.txt" "$dir/checksums.txt.sig" --sums) || exit 1

sum() {
  s=$(printf '%s\n' "$sums" | awk -v k="$1" '$1 == k { print $2 }')
  case "$s" in
    *[!0-9a-f]* | "") echo "bad checksum for $1" >&2; exit 1 ;;
  esac
  [ ${#s} -eq 64 ] || { echo "bad checksum for $1" >&2; exit 1; }
  printf '%s' "$s"
}
# Compute first: a failure inside the heredoc would not stop the script.
darwin_arm64=$(sum darwin_arm64) || exit 1
darwin_amd64=$(sum darwin_amd64) || exit 1
linux_arm64=$(sum linux_arm64) || exit 1
linux_amd64=$(sum linux_amd64) || exit 1

base="https://github.com/pranavjayakumar/terminal-chat/releases/download/$tag"
out="$root/Formula/tc.rb"
mkdir -p "$root/Formula"
cat > "$out" <<EOF
# Generated by scripts/brew-formula.sh from the signed checksums.txt of $tag. Do not edit by hand.
class Tc < Formula
  desc "Lightweight end-to-end encrypted team chat for the terminal"
  homepage "https://github.com/pranavjayakumar/terminal-chat"
  license :cannot_represent

  on_macos do
    on_arm do
      url "$base/tc_darwin_arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$base/tc_darwin_amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$base/tc_linux_arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/tc_linux_amd64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "tc"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/tc --version")
  end
end
EOF
echo "wrote $out" >&2
