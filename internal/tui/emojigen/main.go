// Command emojigen writes internal/tui/emoji_data.go, the emoji table behind
// the picker, ":" completion and ":shortcode:" conversion.
//
// Sources (fetched at generate time only; nothing is downloaded at run time):
//   - GitHub gemoji, MIT License, Copyright (c) 2019 GitHub, Inc.
//     https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json
//     (emoji, Slack-compatible aliases, tags, category)
//   - Unicode emoji-data.txt (Unicode License v3), for Emoji_Presentation
//     https://www.unicode.org/Public/15.1.0/ucd/emoji/emoji-data.txt
//
// Only emoji that terminals draw as one wide cell are kept: a single
// code point with Emoji_Presentation=Yes, or a base plus U+FE0F that
// measures 2 cells. ZWJ sequences, skin tones, keycaps and flags are
// dropped, and so is anything newer than Unicode 13.0, which older
// terminals and fonts measure or draw wrongly.
//
// Run: go generate ./internal/tui (or go run ./internal/tui/emojigen -out
// internal/tui/emoji_data.go; -db and -props read local copies instead).
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/rivo/uniseg"
)

const (
	dbURL    = "https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json"
	propsURL = "https://www.unicode.org/Public/15.1.0/ucd/emoji/emoji-data.txt"
	maxVer   = 13.0
)

// Category order is the picker's tab order.
var cats = map[string]int{
	"Smileys & Emotion": 0,
	"People & Body":     1,
	"Animals & Nature":  2,
	"Food & Drink":      3,
	"Activities":        4,
	"Travel & Places":   5,
	"Objects":           6,
	"Symbols":           7,
}

// stop words carry nothing for search ("face with tears of joy").
var stop = map[string]bool{"with": true, "of": true, "the": true, "and": true, "on": true, "in": true, "at": true, "for": true, "to": true}

type entry struct {
	Emoji       string   `json:"emoji"`
	Description string   `json:"description"`
	Category    string   `json:"category"`
	Aliases     []string `json:"aliases"`
	Tags        []string `json:"tags"`
	Version     string   `json:"unicode_version"`
}

func main() {
	out := flag.String("out", "emoji_data.go", "file to write")
	db := flag.String("db", "", "local gemoji emoji.json (default: download)")
	props := flag.String("props", "", "local emoji-data.txt (default: download)")
	flag.Parse()

	var entries []entry
	if err := json.Unmarshal(read(*db, dbURL), &entries); err != nil {
		log.Fatalf("parsing gemoji: %v", err)
	}
	pres := presentation(read(*props, propsURL))

	var b bytes.Buffer
	b.WriteString("// Code generated by emojigen from GitHub gemoji (MIT); DO NOT EDIT.\n\npackage tui\n\nvar emojiTable = []emojiDef{\n")
	seen := map[string]bool{}
	n := 0
	for _, e := range entries {
		cat, ok := cats[e.Category]
		if !ok || !keep(e, pres) {
			continue
		}
		var names []string
		for _, a := range e.Aliases {
			if a = clean(a); a != "" && !seen[a] {
				seen[a] = true
				names = append(names, a)
			}
		}
		if len(names) == 0 {
			continue
		}
		var keys []string
		have := map[string]bool{}
		for _, n := range names {
			have[n] = true
		}
		for _, w := range append(append([]string{}, e.Tags...), strings.Fields(e.Description)...) {
			if w = clean(strings.ToLower(w)); len(w) > 1 && !have[w] && !stop[w] {
				have[w] = true
				keys = append(keys, w)
			}
		}
		fmt.Fprintf(&b, "\t{%q, %q, %q, %d},\n", e.Emoji, strings.Join(names, " "), strings.Join(keys, " "), cat)
		n++
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("formatting: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %d emoji (%d bytes) to %s", n, len(src), *out)
}

func keep(e entry, pres map[rune]bool) bool {
	if v, err := strconv.ParseFloat(e.Version, 64); err == nil && v > maxVer {
		return false
	}
	rs := []rune(e.Emoji)
	switch {
	case len(rs) == 1:
		return pres[rs[0]]
	case len(rs) == 2 && rs[1] == 0xFE0F:
		return uniseg.StringWidth(e.Emoji) == 2
	}
	return false
}

// clean keeps the characters a shortcode may have: a-z, 0-9, _, + and -.
func clean(s string) string {
	return strings.Map(func(r rune) rune {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '_', r == '+', r == '-':
			return r
		}
		return -1
	}, s)
}

// presentation parses the Emoji_Presentation code points of emoji-data.txt.
func presentation(data []byte) map[rune]bool {
	out := map[rune]bool{}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		cps, prop, ok := strings.Cut(line, ";")
		if !ok || strings.TrimSpace(prop) != "Emoji_Presentation" {
			continue
		}
		lo, hi, _ := strings.Cut(strings.TrimSpace(cps), "..")
		if hi == "" {
			hi = lo
		}
		a, err1 := strconv.ParseUint(lo, 16, 32)
		z, err2 := strconv.ParseUint(hi, 16, 32)
		if err1 != nil || err2 != nil {
			log.Fatalf("bad emoji-data line %q", sc.Text())
		}
		for r := a; r <= z; r++ {
			out[rune(r)] = true
		}
	}
	if len(out) == 0 {
		log.Fatal("no Emoji_Presentation code points found")
	}
	return out
}

func read(path, url string) []byte {
	if path != "" {
		b, err := os.ReadFile(path)
		if err != nil {
			log.Fatal(err)
		}
		return b
	}
	c := &http.Client{Timeout: 30 * time.Second}
	resp, err := c.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	b, err := io.ReadAll(io.LimitReader(resp.Body, 8<<20))
	if err != nil {
		log.Fatal(err)
	}
	return b
}
